const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const http = require('node:http');
const { chromium } = require('playwright');

(async () => {
  const root = path.resolve(__dirname, '..');
  const evidence = path.join(root, 'docs');
  const server = http.createServer((req, res) => {
    res.setHeader('Content-Type', 'text/html; charset=utf-8');
    res.end(`<!doctype html><title>${req.url === '/notes' ? '调研笔记' : '项目资料'}</title><h1>Omni Plus test fixture</h1><p>Synthetic test page; no personal browsing data.</p>`);
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  const extensionPath = path.join(root, 'src');
  let context;
  try {
    context = await chromium.launchPersistentContext('', {
      channel: 'chromium', headless: true, acceptDownloads: true,
      viewport: { width: 1180, height: 940 },
      args: [`--disable-extensions-except=${extensionPath}`, `--load-extension=${extensionPath}`],
    });
    context.setDefaultTimeout(15000);
    const worker = context.serviceWorkers()[0] || await context.waitForEvent('serviceworker');
    const id = worker.url().split('/')[2];
    const pages = [];
    for (const route of ['/research', '/research', '/notes']) {
      const page = await context.newPage();
      await page.goto(base + route);
      pages.push(page);
    }
    const exportPage = await context.newPage();
    await exportPage.goto(`chrome-extension://${id}/export.html`);
    await exportPage.getByRole('button', { name: '下载 .md 文件' }).waitFor({ state: 'visible' });
    await exportPage.waitForFunction(() => !document.getElementById('download').disabled);
    let markdown = await exportPage.locator('#preview').inputValue();
    assert.equal((markdown.match(/^- /gm) || []).length, 2);
    assert.ok(markdown.indexOf('/research') < markdown.indexOf('/notes'));
    assert.ok((await exportPage.locator('#summary').innerText()).includes('去除 1 个重复'));
    await exportPage.getByLabel('相同地址只保留一次').uncheck();
    assert.equal(((await exportPage.locator('#preview').inputValue()).match(/^- /gm) || []).length, 3);
    await exportPage.getByLabel('相同地址只保留一次').check();

    // Window isolation: the other window's synthetic page must not appear.
    await worker.evaluate(url => chrome.windows.create({ url }), base + '/other-window');
    await exportPage.getByRole('button', { name: '刷新标签页' }).click();
    await exportPage.waitForFunction(() => !document.getElementById('refresh').disabled);
    markdown = await exportPage.locator('#preview').inputValue();
    assert.ok(!markdown.includes('/other-window'));

    // Check the generated bytes rather than assuming a click means success.
    const pending = exportPage.waitForEvent('download');
    await exportPage.getByRole('button', { name: '下载 .md 文件' }).click();
    const download = await pending;
    const downloaded = await fs.readFile(await download.path(), 'utf8');
    assert.equal(downloaded, markdown);
    assert.match(download.suggestedFilename(), /^omni-tabs-\d{4}-\d{2}-\d{2}\.md$/);
    // Exercise both clipboard callbacks without touching the user's OS clipboard.
    await exportPage.evaluate(() => Object.defineProperty(navigator, 'clipboard', {
      configurable: true, value: { writeText: async text => { window.__testCopied = text; } },
    }));
    await exportPage.getByRole('button', { name: '复制 Markdown' }).click();
    await exportPage.waitForFunction(() => document.getElementById('feedback').textContent === 'Markdown 已复制。');
    assert.equal(await exportPage.evaluate(() => window.__testCopied), markdown);
    await exportPage.evaluate(() => { navigator.clipboard.writeText = async () => { throw new Error('Synthetic denial'); }; });
    await exportPage.getByRole('button', { name: '复制 Markdown' }).click();
    await exportPage.waitForFunction(() => document.getElementById('feedback').textContent.includes('已选中'));

    // Use the real content script command to open the exporter.
    await pages[0].bringToFront();
    await worker.evaluate(async url => {
      const [tab] = await chrome.tabs.query({ url });
      await chrome.windows.update(tab.windowId, { focused: true });
      await chrome.tabs.update(tab.id, { active: true });
      await chrome.tabs.sendMessage(tab.id, { request: 'open-omni' });
    }, base + '/research');
    const command = pages[0].locator('.omni-item').filter({ hasText: 'Export tabs as Markdown 导出标签页' });
    await command.waitFor({ state: 'visible' });
    assert.equal(await pages[0].locator('#omni-extension').count(), 1);
    const newPagePromise = context.waitForEvent('page');
    await command.hover();
    await command.click();
    const commandPage = await newPagePromise;
    await commandPage.waitForURL(`chrome-extension://${id}/export.html`);
    assert.ok(await commandPage.getByRole('heading', { name: '链接预览' }).isVisible());
    await commandPage.close();

    await exportPage.bringToFront();
    await exportPage.getByRole('button', { name: '刷新标签页' }).click();
    await exportPage.waitForFunction(() => !document.getElementById('refresh').disabled);
    await exportPage.screenshot({ path: path.join(evidence, 'export-desktop.png'), fullPage: true });
    await exportPage.setViewportSize({ width: 390, height: 844 });
    assert.ok(await exportPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await exportPage.screenshot({ path: path.join(evidence, 'export-mobile.png'), fullPage: true });

    // Empty and failure states use real extension UI with a simulated API failure only here.
    for (const page of pages) await page.close();
    await exportPage.getByRole('button', { name: '刷新标签页' }).click();
    await exportPage.waitForFunction(() => !document.getElementById('refresh').disabled);
    assert.equal(await exportPage.locator('#preview').inputValue(), '');
    assert.equal(await exportPage.getByRole('button', { name: '下载 .md 文件' }).isDisabled(), true);
    await exportPage.evaluate(() => { chrome.tabs.query = async () => { throw new Error('Synthetic API failure'); }; });
    await exportPage.getByRole('button', { name: '刷新标签页' }).click();
    await exportPage.waitForFunction(() => document.getElementById('summary').textContent === '读取标签页失败');
    assert.equal(await exportPage.getByRole('button', { name: '复制 Markdown' }).isDisabled(), true);

    const result = { status: 'passed', browser: context.browser()?.version(), extension_id: id,
      checked_at: new Date().toISOString(), checks: ['MV3 loaded in isolated Chromium', 'real tabs queried',
      'exact URL deduplication toggle', 'tab order', 'window isolation', 'download bytes match preview',
      'simulated clipboard success and denial with explicit manual fallback', 'real Omni command opens exporter',
      'desktop and mobile layout', 'empty state', 'simulated API error disables export'],
      limits: 'Synthetic pages only; clipboard success/denial and API failure are simulated. Personal Chrome profile and OS clipboard are not accessed.' };
    await fs.writeFile(path.join(evidence, 'verification.json'), JSON.stringify(result, null, 2) + '\n');
    console.log(JSON.stringify(result, null, 2));
  } finally {
    await context?.close();
    await new Promise(resolve => server.close(resolve));
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
